"""Generate db/migrations/011_pillars.sql from db/content/pillars/*.py.

Upgrades module:  KIND="upgrades",  KEY=(make, model, gen), CATEGORIES=[...], TITLE, META, FAQ, ARTICLE
Explainer module: KIND="explainer", SLUG="hard-vs-soft-tonneau-covers", CATEGORIES=[...], TITLE, META, FAQ, ARTICLE
published_at is set by the first insert only (stable datePublished).
"""
import glob, importlib.util, json, os
here = os.path.dirname(__file__)

def modules():
    for p in sorted(glob.glob(os.path.join(here, "pillars", "*.py"))):
        if p.endswith("__init__.py"): continue
        spec = importlib.util.spec_from_file_location(os.path.basename(p)[:-3], p)
        m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); yield m

def lit(s):  # dollar-quote with a tag the content cannot contain
    assert "$p$" not in s, "content must not contain $p$"
    return f"$p${s}$p$"

if __name__ == "__main__":
    out = ["-- 011_pillars.sql — GENERATED by db/content/build_pillars_sql.py; edit db/content/pillars/*.py.",
           "SET client_min_messages = warning;", ""]
    n = 0
    for m in modules():
        faq = json.dumps([{"q": q, "a": a} for q, a in m.FAQ], ensure_ascii=False)
        art = json.dumps(m.ARTICLE, ensure_ascii=False)
        cats = "ARRAY[" + ",".join(f"'{c}'" for c in m.CATEGORIES) + "]::text[]"
        if m.KIND == "upgrades":
            make, model, gen = m.KEY
            slug = f"{make}/{model}/{gen}"
            vid = f"(SELECT v.id FROM vehicles v JOIN makes mk ON mk.id=v.make_id WHERE mk.slug='{make}' AND v.model_slug='{model}' AND v.gen_slug='{gen}')"
        else:
            slug, vid = m.SLUG, "NULL"
        out.append(f"""INSERT INTO pillar_pages (kind, slug, vehicle_id, category_slugs, title, meta_desc, faq, article)
VALUES ('{m.KIND}', '{slug}', {vid}, {cats}, {lit(m.TITLE)}, {lit(m.META)}, {lit(faq)}::jsonb, {lit(art)}::jsonb)
ON CONFLICT (slug) DO UPDATE SET kind=EXCLUDED.kind, vehicle_id=EXCLUDED.vehicle_id, category_slugs=EXCLUDED.category_slugs,
  title=EXCLUDED.title, meta_desc=EXCLUDED.meta_desc, faq=EXCLUDED.faq, article=EXCLUDED.article, updated_at=now();
""")
        n += 1
    open(os.path.join(here, "..", "migrations", "011_pillars.sql"), "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote 011_pillars.sql: {n} pillar page(s)")
